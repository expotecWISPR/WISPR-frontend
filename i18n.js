  // Un texto con {0}, {1}... se vuelve un patrón. Los más largos van primero
  // para que uno general ("Módulo {0}") no le gane a uno específico.
  const patterns = Object.entries(EN)
    .filter(([source]) => /\{#?\d\}/.test(source))
    .map(([source, target]) => {
      const regex = source
        .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
        .replace(/\\\{#(\d)\\\}/g, "([\\d.,]+)")
        .replace(/\\\{(\d)\\\}/g, "([\\s\\S]*?)");
      const order = [...source.matchAll(/\{#?(\d)\}/g)].map(match => Number(match[1]));
      return { regex: new RegExp(`^${regex}$`), target, order, weight: source.replace(/\{#?\d\}/g, "").length };
    })
    .sort((a, b) => b.weight - a.weight);

  function translate(text) {
    if (Object.hasOwn(EN, text)) return EN[text];
    for (const { regex, target, order } of patterns) {
      const match = text.match(regex);
      if (!match) continue;
      return target.replace(/\{(\d)\}/g, (_, index) => {
        const value = match[order.indexOf(Number(index)) + 1] ?? "";
        return tr(value);
      });
    }
    return null;
  }

  function getLang() {
    try {
      if (localStorage.getItem(LANG_KEY) === "en") return "en";
    } catch {}
    return "es";
  }

  let lang = getLang();
  const cache = new Map();
  document.documentElement.lang = lang;

  // Traduce conservando los espacios de los extremos: muchos textos se pegan
  // a un ícono o a un <strong> vecino (" retos", "puesto ").
  function tr(text) {
    if (lang !== "en" || typeof text !== "string") return text;
    if (cache.has(text)) return cache.get(text);
    const core = text.trim();
    let result = text;
    if (/[A-Za-zÁÉÍÓÚÑáéíóúñ]/.test(core)) {
      const translated = translate(core);
      if (translated !== null) result = text.replace(core, () => translated);
    }
    cache.set(text, result);
    return result;
  }

  function setLang(next) {
    lang = next === "en" ? "en" : "es";
    document.documentElement.lang = lang;
    try { localStorage.setItem(LANG_KEY, lang); } catch {}
  }

  window.I18N = { tr, setLang, lang: () => lang, locale: () => (lang === "en" ? "en-US" : "es-CR") };
